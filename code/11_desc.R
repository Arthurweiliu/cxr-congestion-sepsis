setwd("F:/openclaw_workspace/CXR_congestion")
d <- read.csv("data/base.csv", stringsAsFactors=FALSE)
d$female <- as.integer(d$gender=="F")
a <- d[!is.na(d$cong_hybrid) & !is.na(d$fb72_mlkg) & !is.na(d$death30),]
cat("N", nrow(a), "deaths", sum(a$death30), "\n")
cat("age median/IQR", median(a$age), quantile(a$age,c(.25,.75)), "\n")
cat("female %", round(100*mean(a$female),1), "\n")
cat("sofa median/IQR", median(a$sofa_score), quantile(a$sofa_score,c(.25,.75),na.rm=TRUE), "\n")
cat("fb median/IQR", median(a$fb72_mlkg), quantile(a$fb72_mlkg,c(.25,.75)), "\n")
cat("cong+ n", sum(a$cong_hybrid==1), "pct", round(100*mean(a$cong_hybrid),1), "\n")
tb <- table(cong=a$cong_hybrid, fb=as.integer(a$fb72_mlkg>0)); print(tb)
cat("of cong+: pct fb>0", round(100*tb[2,2]/sum(tb[2,]),1), " pct fb<=0", round(100*tb[2,1]/sum(tb[2,]),1), "\n")
cat("of cong-: pct fb>0", round(100*tb[1,2]/sum(tb[1,]),1), "\n")
cat("overall agreement", round(100*(tb[1,1]+tb[2,2])/sum(tb),1), "\n")
