setwd("F:/openclaw_workspace/CXR_congestion")
.libPaths(c("F:/openclaw_workspace/Rlibs", "F:/openclaw_workspace/R_lib", .libPaths()))
suppressPackageStartupMessages({ library(splines); library(pROC) })
f <- read.csv("data/final_with_lac.csv")
f$grp <- factor(f$grp, levels = c("A","B","C","D"))
f$fb10 <- f$fb72_mlkg / 10
f$cong <- as.integer(f$cong_hybrid)
covs <- c("age","female","sofa_score","lac","vent24","vaso24","hf","ckd")
cc <- f[complete.cases(f[, c("death30", covs)]), ]
cat("n =", nrow(cc), " deaths =", sum(cc$death30), "\n")
m0 <- glm(death30 ~ age+female+sofa_score+lac+vent24+vaso24+hf+ckd, cc, family=binomial)
m1 <- glm(death30 ~ grp+age+female+sofa_score+lac+vent24+vaso24+hf+ckd, cc, family=binomial)
a0 <- as.numeric(auc(roc(cc$death30, fitted(m0), quiet=TRUE)))
a1 <- as.numeric(auc(roc(cc$death30, fitted(m1), quiet=TRUE)))
cat(sprintf("base %.4f -> base+4grp %.4f  dAUC %.4f\n", a0, a1, a1-a0))
set.seed(7); B <- 500; p0 <- fitted(m0); p1 <- fitted(m1); y <- cc$death30; n <- nrow(cc)
d <- replicate(B, { s <- sample(n, n, TRUE)
  as.numeric(auc(roc(y[s], p1[s], quiet=TRUE))) - as.numeric(auc(roc(y[s], p0[s], quiet=TRUE))) })
cat(sprintf("bootstrap 95%% CI %.4f to %.4f\n", quantile(d,.025), quantile(d,.975)))
